// Gleichstufige Teilungen der Oktave, deren Stufen 1 bis n − 1 in der Liste stehen.
export const EDOS = [12, 19, 22, 24, 31, 53];

// Baut die Liste aus `Wert | Name`-Zeilen und den EDO-Stufen, nach Cent aufsteigend.
// Gleiche Tonhöhe (auf 0,01 Cent gerundet) wird ein Eintrag mit mehreren Namen; ein Verhältnis geht als Wert vor.
// Ein Eintrag: `{ value, cents, names }`.
export function buildIntervals(lines, edos) {
  const candidates = lines.map((line) => {
    const [value, name] = line.split("|").map((part) => part.trim());
    return { value, name };
  });
  for (const n of edos) {
    for (let step = 1; step < n; step++) {
      candidates.push({ value: (1200 * step / n).toFixed(2), name: `${step}. Stufe ${n}-EDO` });
    }
  }
  const byPitch = new Map();
  for (const { value, name } of candidates) {
    const ratio = parseTuningValue(value);
    if (ratio === null) throw new Error(`Intervall nicht lesbar: „${value}“`);
    const cents = 1200 * Math.log2(ratio);
    const key = cents.toFixed(2);
    const entry = byPitch.get(key);
    if (!entry) {
      byPitch.set(key, { value, cents, names: [name] });
    } else {
      entry.names.push(name);
      if (isCents(entry.value) && !isCents(value)) Object.assign(entry, { value, cents });
    }
  }
  return [...byPitch.values()].sort((a, b) => a.cents - b.cents);
}

function isCents(value) {
  return value.includes(".");
}

export const INTERVALS = buildIntervals(WIKIPEDIA_LINES, EDOS);

// Text eines Eintrags: `5/4 · Just major third · 386.31 ct (−14)`; die Klammer ist die Abweichung zur nächsten
// 12-EDO-Stufe, mehrere Namen stehen durch „ / “ getrennt.
export function formatInterval(entry) {
  const deviation = entry.cents - 100 * Math.round(entry.cents / 100);
  return `${entry.value} · ${entry.names.join(" / ")} · ${entry.cents.toFixed(2)} ct (${formatCents(deviation)})`;
}

// Stelle des Eintrags, der einem Wert (Verhältnis oder Cent-Wert als Text) am nächsten liegt, oder −1, wenn
// der Wert nicht lesbar ist. Dorthin scrollt die Liste; angeboten werden trotzdem alle Einträge.
export function nearestIntervalIndex(intervals, value) {
  const ratio = parseTuningValue(value);
  if (ratio === null || intervals.length === 0) return -1;
  const cents = 1200 * Math.log2(ratio);
  let best = 0;
  for (let i = 1; i < intervals.length; i++) {
    if (Math.abs(intervals[i].cents - cents) < Math.abs(intervals[best].cents - cents)) best = i;
  }
  return best;
}
